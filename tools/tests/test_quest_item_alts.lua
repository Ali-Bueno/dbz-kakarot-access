-- Regression: a quest collection must match ANY item a spot can drop, on ANY open checklist row.
--
-- Player report 2026-11-09 (Goku's "Animorphaline Accident" sub-story): the HUD asked for
-- "Hierba de alta calidad 17/3, Caracol de río carnoso 0/4, Asta de gacela dorada 0/1" and the
-- radar found nothing. Two causes, both pinned here:
--   1. `Lost_Snail_01` resolved to its EARLIEST drop ("river shrimp", item 36015), so it never
--      matched the snail the quest asks for (36019, one of its later-episode drops).
--   2. Only the FIRST unfinished row was ever looked for.
--
-- Runs OFFLINE under the vendored Lua 5.4 (tools/run-lua-tests.ps1); nothing touches the game.

local here = arg[0]:match("^(.*[\\/])") or "./"
package.path = here .. "..\\..\\mod\\KakarotAccess\\Scripts\\?.lua;" .. package.path

local function stub(name, members)
    setmetatable(members, { __index = function(_, k)
        error(("harness stub '%s' has no member '%s' - declare it in the test"):format(name, k), 2)
    end })
    package.preload[name] = function() return members end
    return members
end

stub("ui_core", {})
stub("speech", {})
stub("audio", {})
stub("i18n", {})
stub("ui_registry", {})
stub("race_guide", {})
stub("raycast", {})
stub("mem", {})
stub("transition", { on_begin = function() end })
-- Generated data, reduced to the rows under test (the real files are pak-derived).
package.preload["item_drop_ids"] = function()
    return { Lost_Snail_01 = 36015, Lost_Seaweed_Fixed = 36029,
             DLC03_Area02_Animal_GoldGazelle_02_Fixed = 31009 }
end
package.preload["item_drop_alts"] = function()
    return { Lost_Snail_01 = { 36019, 36022 }, DLC03_Area02_Animal_GoldGazelle_02_Fixed = { 53017 } }
end

-- course_teachers.lua, reduced to one key of each shape (generated by dump_course_teachers.py).
package.preload["course_teachers"] = function()
    return { mnq = { ["C1m13|mad0001s"] = { 96002 }, ["C3m54|fag0001s"] = { 96009 } },
             step = { ["D3m09010|mad0001s"] = { 96002 }, ["D3m09011|mad0001s"] = { 96003 } },
             quest = { ["Sub_Cooking_01"] = { 96004 } } }
end

local Nav = require("nav_tracker")

-- The game's message table, doubled: ids -> the es_MX names read live on 2026-11-09.
local NAMES = {
    ["Item_36015_Name"] = "Camarón de río",
    ["Item_36019_Name"] = "Caracol de río carnoso",
    ["Item_36022_Name"] = "Huevo gelatinoso",
    ["Item_36029_Name"] = "Algas marinas",
    ["Item_31009_Name"] = "Carne de gacela dorada extra",
    ["Item_53017_Name"] = "Asta de gacela dorada",
}
Nav._message_text = function(id) return NAMES[id] end

local fails = 0
local function check(cond, what)
    if cond then print("ok   - " .. what) else fails = fails + 1; print("FAIL - " .. what) end
end

-- The requirement exactly as quest_objective builds it: first open row + `all` open rows.
local snail = { name = "Caracol de río carnoso", got = 0, need = 4, kind = "sub" }
local antler = { name = "Asta de gacela dorada", got = 0, need = 1, kind = "sub" }
local req = { name = snail.name, got = 0, need = 4, kind = "sub", all = { snail, antler } }

-- drop ids: primary first, then the alternates; an unknown slug has none
local ids = Nav._drop_ids_of("Lost_Snail_01")
check(ids[1] == 36015 and ids[2] == 36019 and ids[3] == 36022, "snail spot lists primary + alternates")
check(#Nav._drop_ids_of("No_Such_Slug") == 0, "unknown slug yields no ids")
check(#Nav._drop_ids_of("Lost_Seaweed_Fixed") == 1, "a slug without alternates yields its primary only")

-- the wanted drop is found among the alternates, on the first row
check(Nav._wanted_drop_name("Lost_Snail_01", req) == "Caracol de río carnoso",
    "snail spot matches the snail row through its later-episode drop")
-- ... and on a LATER row (the antler is row 2)
check(Nav._wanted_drop_name("DLC03_Area02_Animal_GoldGazelle_02_Fixed", req) == "Asta de gacela dorada",
    "golden gazelle matches the second open row through its alternate drop")
-- a spot that drops nothing wanted stays unmatched
check(Nav._wanted_drop_name("Lost_Seaweed_Fixed", req) == nil, "unrelated spot is not promoted")
check(Nav._wanted_drop_name("Lost_Snail_01", nil) == nil, "no requirement, no match")

-- _req_row returns the row whose counts belong in the label
check(Nav._req_row(req, "Asta de gacela dorada") == antler, "row lookup finds the second row")
check(Nav._req_row(req, "Algas marinas") == nil, "row lookup rejects an unwanted item")
-- a requirement without `all` (older shape) still works as a single row
check(Nav._req_row({ name = "Algas marinas", got = 1, need = 3 }, "Algas marinas") ~= nil,
    "single-row requirement still matches")

-- full-course meal teachers (player request 2026-11-09): talk id -> recipe items
local function first(t) return t and t[1] end
check(first(Nav._course_teacher("C1m13041_mad0001s")) == 96002, "the step that grants the recipe matches")
check(first(Nav._course_teacher("C1m13011_mad0001s")) == 96002, "an earlier step of the same mini-quest matches")
check(first(Nav._course_teacher("C3m54051_fag0001s_p1")) == 96009, "a suffixed talk variant matches")
check(Nav._course_teacher("C3m54073_mad0002s") == nil, "another NPC of the same mini-quest does not")
check(first(Nav._course_teacher("D3m09011_mad0001s")) == 96003, "a DLC teacher is keyed by its own step")
check(Nav._course_teacher("D3m09017_mad0001s") == nil, "another step of that mini-quest teaches nothing")
check(first(Nav._course_teacher("Sub_Cooking_01_Mob_01")) == 96004, "a sub-quest client matches by quest prefix")
check(Nav._course_teacher("Sub_Cooking_010_Mob_01") == nil, "the quest prefix needs a word boundary")
check(Nav._course_teacher("Sub_Npc086_01_Npc086_03") == nil, "an unrelated quest NPC does not match")
check(Nav._course_teacher(nil) == nil and Nav._course_teacher("") == nil, "no talk id, no match")

if fails > 0 then
    print(("%d check(s) FAILED"):format(fails))
    os.exit(1)
end
print("all checks passed")
